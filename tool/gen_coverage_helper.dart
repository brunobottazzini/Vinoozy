// Generates test/coverage_helper_test.dart, which imports every Dart file under
// lib/ (generated translations included). `flutter test --coverage` only
// reports files loaded by some test, so without this helper a file with no
// tests would be invisible instead of counting as 0% (NFR7.1: 80% of lines on
// all of lib/, no exclusions).
//
// Usage: dart run tool/gen_coverage_helper.dart
import 'dart:io';

void main() {
  final libDir = Directory('lib');
  if (!libDir.existsSync()) {
    stderr.writeln(
      'gen_coverage_helper: run from the project root (lib/ missing)',
    );
    exitCode = 2;
    return;
  }

  final files =
      libDir
          .listSync(recursive: true)
          .whereType<File>()
          .map((f) => f.path.replaceAll(r'\', '/'))
          .where((path) => path.endsWith('.dart'))
          .where((path) => !_isPartFile(File(path)))
          .map((path) => path.substring('lib/'.length))
          .toList()
        ..sort();

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/gen_coverage_helper.dart - do not edit.')
    ..writeln('// Imports every file of lib/ so untested files count as 0%.')
    ..writeln('// ignore_for_file: unused_import, directives_ordering')
    ..writeln();
  for (final path in files) {
    buffer.writeln("import 'package:vinoozy/$path';");
  }
  buffer
    ..writeln()
    ..writeln('void main() {}');

  File('test/coverage_helper_test.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(buffer.toString());
  stdout.writeln('gen_coverage_helper: ${files.length} files imported');
}

bool _isPartFile(File file) =>
    file.readAsLinesSync().any((line) => line.trimLeft().startsWith('part of'));
